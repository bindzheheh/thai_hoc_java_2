package E_4_5;

/**
 * This is a class representing a time (hour, minute, second) of a sound record.
 * @author NguyenVanThai
 * ID:2611130213
 */
public class Time {
	/**
	 * properties
	 */
	private int hour; 
	private int minute; 
	private int second; 

	/**
	 * Constructor: creates a time from the hour, minute and second.
	 */
	public Time(int hour, int minute, int second) {
		this.hour = hour; 
		this.minute = minute; 
		this.second = second; 
	}

}