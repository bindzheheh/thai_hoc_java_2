package E_4_3;

public class Time {
	/**
	 * properties
	 */
	private int hour;
	private int minute;
	private int second;
	/**
	 * constructor
	 * @param hour
	 * @param minute
	 * @param second
	 */
	public Time(int hour, int minute, int second) {
		this.hour = hour;
		this.minute = minute;
		this.second = second;
	}
	

}
