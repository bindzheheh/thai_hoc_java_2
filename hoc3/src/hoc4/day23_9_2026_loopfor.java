package hoc4;
import java.util.Scanner;
public class day23_9_2026_loopfor {
	public static void main(String[]args) throws InterruptedException{
		Scanner scanner = new Scanner(System.in);
		int idk;
		System.out.print("nhập thời gian chờ để xem bất ngờ :");
		idk =scanner.nextInt();
		for(int i = idk;i>0;i--) {
			System.out.printf("thời gian còn lại : %ds\n",i);
			Thread.sleep(1000);
		}
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		System.out.print("thật ra người viết ra code này rất đẹp trai =3 😁😂 ");
		scanner.close();
	}

}
